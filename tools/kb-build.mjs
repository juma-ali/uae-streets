#!/usr/bin/env node
/**
 * Builds / extends data/kb.js — the knowledge base.
 *
 * A street row always resolves to a four-level path, e.g.
 *   Abu Dhabi Emirate » Abu Dhabi » Abu Dhabi » Khalifa City
 *
 *   node tools/kb-build.mjs --area khalifa-city \
 *     --path "Abu Dhabi Emirate,Abu Dhabi,Abu Dhabi,Khalifa City" \
 *     --osm relation/13251355 --bbox 24.3905,54.5040,24.4496,54.6422
 *
 * Reads the Overpass response cached by tools/osm-district.mjs (run that first),
 * so this never touches the network.
 *
 * Data © OpenStreetMap contributors, ODbL 1.0.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
const arg = (name, fallback) => {
  const i = args.indexOf(name);
  return i > -1 && args[i + 1] ? args[i + 1] : fallback;
};

const areaId = arg("--area", "");
const emirateId = arg("--emirate", "");
const pathArg = arg("--path", "");
const osmRef = arg("--osm", "");
const bbox = arg("--bbox", "");
const coverageNote = arg("--note", "");

const mode = areaId ? "area" : emirateId ? "emirate" : "";
if (!mode) {
  console.error(
    "Usage:\n" +
      '  node tools/kb-build.mjs --area <id> --path "L1,L2,L3,L4" [--osm relation/id]\n' +
      "  node tools/kb-build.mjs --emirate abu-dhabi --osm relation/3766481"
  );
  process.exit(2);
}

const path = pathArg ? pathArg.split(",").map((s) => s.trim()).filter(Boolean) : [];
if (mode === "area" && path.length !== 4) {
  console.error("--path needs exactly four levels: Emirate, City, Area, District");
  process.exit(2);
}

const root = fileURLToPath(new URL("..", import.meta.url));
const kbPath = root + "data/kb.js";
const cacheDir = root + ".cache";

/* ---------- find the cached Overpass response ---------- */
if (!existsSync(cacheDir)) {
  console.error("No .cache/ — run tools/osm-district.mjs or tools/kb-collect.mjs first.");
  process.exit(1);
}
const prefix = mode === "area" ? areaId + "-" : "emirate-" + emirateId + "-";
const cacheFile = readdirSync(cacheDir).find((f) => f.startsWith(prefix));
if (!cacheFile) {
  console.error(`No cached Overpass result ${prefix}*.json in .cache/`);
  process.exit(1);
}
const raw = JSON.parse(readFileSync(cacheDir + "/" + cacheFile, "utf8"));

/* ---------- collapse ways into one row per name ---------- */
const slug = (s) =>
  String(s || "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 80);

/* A name with no words in it — "Road 1b", "Street 112", "شارع 7" — has no story
   and is deliberately left out of the knowledge base. */
const numericOnly = (en, ar) => {
  const words = (s) =>
    String(s || "")
      .toLowerCase()
      // Latin road words need \b; Arabic ones must NOT use it — \b is ASCII-only,
      // so "شارع" would never match and every Arabic name would look non-numeric.
      .replace(/\b(street|road|st|rd|ave|avenue|lane)\b/gi, " ")
      .replace(/شارع|طريق|جادة/g, " ")
      .replace(/\d+\s*(st|nd|rd|th)\b/gi, " ") // 1st, 2nd …
      .replace(/[0-9]+[a-z]?/gi, " ") // 112, 1b
      .replace(/[^\p{L}\s]/gu, " ")
      .replace(/\s+/g, "");
  return words(en).length === 0 && words(ar).length === 0;
};

const byName = new Map();
let skippedNumeric = 0;
for (const el of raw.elements || []) {
  const t = el.tags || {};
  const en = t["name:en"] || t.name || "";
  const ar = t["name:ar"] || "";
  if (!en && !ar) continue;
  if (numericOnly(en, ar)) {
    skippedNumeric++;
    continue;
  }
  const key = (en || ar).toLowerCase();
  const prev = byName.get(key);
  if (!prev || (!prev.name_ar && ar)) {
    const scope = mode === "area" ? areaId : emirateId;
    byName.set(key, {
      id: scope + "/" + slug(en || ar),
      area: mode === "area" ? areaId : null,
      emirate: mode === "emirate" ? emirateId : null,
      name_en: en || ar,
      name_ar: ar,
      osm: "way/" + el.id,
      kind: t.highway || "",
      lat: el.center ? Number(el.center.lat.toFixed(6)) : null,
      lon: el.center ? Number(el.center.lon.toFixed(6)) : null,
    });
  }
}
const streets = [...byName.values()];

/* ---------- load, merge, write ---------- */
let kb = { meta: {}, areas: [], emirates: [], streets: [] };
if (existsSync(kbPath)) {
  const w = {};
  new Function("window", readFileSync(kbPath, "utf8"))(w);
  if (w.KB) kb = w.KB;
}
kb.emirates = kb.emirates || [];

kb.meta = {
  license: "ODbL 1.0",
  attribution: "© OpenStreetMap contributors — https://www.openstreetmap.org/copyright",
  note: "Generated by tools/kb-build.mjs. Do not edit by hand.",
};

if (mode === "area") {
  const area = {
    id: areaId,
    path,
    osm: osmRef || "",
    bbox: bbox ? bbox.split(",").map(Number) : null,
    street_count: streets.length,
  };
  const i = kb.areas.findIndex((a) => a.id === areaId);
  if (i > -1) kb.areas[i] = area;
  else kb.areas.push(area);
  kb.areas.sort((a, b) => a.path.join("/").localeCompare(b.path.join("/")));
  kb.streets = kb.streets.filter((s) => s.area !== areaId).concat(streets);
} else {
  // A district already in the KB sits inside this emirate's bbox, so drop the
  // district rows from the emirate-level set — one way, one row.
  const known = new Set(kb.streets.filter((s) => s.area).map((s) => s.osm));
  const deduped = streets.filter((s) => !known.has(s.osm));
  const duplicates = streets.length - deduped.length;

  const rec = {
    id: emirateId,
    osm: osmRef || "",
    bbox: bbox ? bbox.split(",").map(Number) : null,
    street_count: deduped.length,
    note: coverageNote || "Collected at emirate level; district assignment is a later step.",
  };
  const i = kb.emirates.findIndex((e) => e.id === emirateId);
  if (i > -1) kb.emirates[i] = rec;
  else kb.emirates.push(rec);
  kb.emirates.sort((a, b) => a.id.localeCompare(b.id));
  kb.streets = kb.streets.filter((s) => s.emirate !== emirateId).concat(deduped);
  if (duplicates) console.log(`deduped: ${duplicates} streets already covered by a district`);
  streets.length = 0;
  streets.push(...deduped);
}

kb.streets.sort(
  (a, b) => (a.area || "").localeCompare(b.area || "") || a.name_en.localeCompare(b.name_en)
);

const header =
  "/* Knowledge base — areas, emirates and their streets, with a four-level path\n" +
  "   where a district has been assigned.\n" +
  "   Data © OpenStreetMap contributors, ODbL 1.0\n" +
  "   Generated by tools/kb-build.mjs — do not edit by hand. */\n\n";

writeFileSync(kbPath, header + "window.KB = " + JSON.stringify(kb, null, 2) + ";\n");

console.log(
  mode === "area" ? `area   : ${path.join(" » ")}` : `emirate: ${emirateId} (no district assignment yet)`
);
console.log(`streets: ${streets.length} in this scope, ${kb.streets.length} total in KB`);
console.log(`skipped: ${skippedNumeric} numeric-only names (Road 1b, Street 112 …)`);
console.log(`file   : data/kb.js  ${Math.round(readFileSync(kbPath).length / 1024)} KB`);
const withAr = streets.filter((s) => s.name_ar).length;
const withCoords = streets.filter((s) => s.lat !== null).length;
console.log(`name:ar: ${withAr}/${streets.length}   coordinates: ${withCoords}/${streets.length}`);
