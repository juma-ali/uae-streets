#!/usr/bin/env node
/**
 * Assigns every KB street to the administrative boundary that contains it, and
 * rebuilds `areas` with a four-level path:
 *
 *   Abu Dhabi Emirate » Abu Dhabi » Abu Dhabi » Al Danah
 *
 * Reads .cache/admin-abu-dhabi.json (from tools/pbf-boundaries.mjs) and rewrites
 * data/kb.js in place.
 *
 *   node tools/kb-districts.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const kbPath = root + "data/kb.js";
const adminPath = root + ".cache/admin-abu-dhabi.json";

/* The same five boxes the collection used — they name the city level where OSM
   has no boundary for it (Al Ain, the Al Dhafra towns). */
const CITY_BOXES = [
  ["Abu Dhabi", 24.26, 54.3, 24.56, 54.78],
  ["Al Ain", 24.1, 55.55, 24.35, 55.9],
  ["Liwa", 23.05, 53.5, 23.9, 54.0],
  ["Ruwais", 24.05, 52.6, 24.2, 52.85],
  ["Sila", 24.0, 51.7, 24.15, 51.95],
];

const slug = (s) =>
  String(s || "")
    .toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, "-")
    .replace(/^-|-$/g, "");

const inRing = (lat, lon, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [yi, xi] = ring[i];
    const [yj, xj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};

const w = {};
new Function("window", readFileSync(kbPath, "utf8"))(w);
const kb = w.KB;

const boundaries = JSON.parse(readFileSync(adminPath, "utf8")).map((b) => {
  let s = 90, n = -90, ww = 180, e = -180, points = 0;
  for (const ring of b.rings) {
    for (const [lat, lon] of ring) {
      if (lat < s) s = lat;
      if (lat > n) n = lat;
      if (lon < ww) ww = lon;
      if (lon > e) e = lon;
      points++;
    }
  }
  return { ...b, bbox: [s, ww, n, e], points };
});

const byLevel = (lvl) => boundaries.filter((b) => b.level === lvl);
const L4 = byLevel(4);
const L5 = byLevel(5);
const L6 = byLevel(6);
const L8 = byLevel(8);

function containing(list, lat, lon) {
  let best = null;
  for (const b of list) {
    const [s, ww, n, e] = b.bbox;
    if (lat < s || lat > n || lon < ww || lon > e) continue;
    if (!b.rings.some((ring) => inRing(lat, lon, ring))) continue;
    if (!best || b.points < best.points) best = b; // tightest wins
  }
  return best;
}

const cityFor = (lat, lon) =>
  (CITY_BOXES.find(([, s, ww, n, e]) => lat >= s && lat <= n && lon >= ww && lon <= e) || [])[0] || "";

/* ---------- assign ---------- */
let assigned = 0;
let unassigned = 0;
const areas = new Map();
const cityFallbacks = new Map();

for (const s of kb.streets) {
  s.area = null;
  const emirateBoundary = L4.find((b) => b.name_en.includes("Abu Dhabi"));
  const city = cityFor(s.lat, s.lon);
  if (city) cityFallbacks.set(city, (cityFallbacks.get(city) || 0) + 1);

  const d8 = containing(L8, s.lat, s.lon);
  if (!d8) { unassigned++; continue; }

  const l6 = containing(L6, s.lat, s.lon);
  const l5 = containing(L5, s.lat, s.lon);

  const path = [
    (emirateBoundary && emirateBoundary.name_en) || "Abu Dhabi Emirate",
    (l5 && l5.name_en) || city || d8.name_en,
    (l6 && l6.name_en) || city || d8.name_en,
    d8.name_en || d8.name_ar,
  ];

  const id = slug(path[3]) + "-" + d8.osm.split("/")[1];
  s.area = id;
  assigned++;

  if (!areas.has(id)) {
    areas.set(id, {
      id,
      path,
      osm: d8.osm,
      bbox: d8.bbox,
      street_count: 0,
      centroid: d8.centroid,
    });
  }
  areas.get(id).street_count++;
}

/* ---------- rebuild areas, drop the hand-made one ---------- */
kb.areas = [...areas.values()]
  .filter((a) => a.street_count > 0)
  .sort((a, b) => a.path.join("/").localeCompare(b.path.join("/")));
kb.areas.forEach((a) => delete a.centroid);

kb.meta.note =
  "Generated by tools/pbf-import.mjs + tools/kb-build.mjs + tools/kb-districts.mjs. " +
  "District assignment uses the tightest OSM administrative boundary (admin_level 8) containing each street's centre.";

writeFileSync(kbPath, "window.KB = " + JSON.stringify(kb, null, 2) + ";\n");

console.log(`assigned : ${assigned} / ${kb.streets.length} streets`);
console.log(`areas    : ${kb.areas.length} districts`);
console.log(`unassigned (no admin_level 8 polygon): ${unassigned}`);
console.log(`cities   : ${[...cityFallbacks.entries()].map(([k, v]) => k + " " + v).join(", ")}`);
console.log("\nsample areas:");
kb.areas.slice(0, 8).forEach((a) => console.log("  " + a.path.join(" » ") + "  (" + a.street_count + ")"));
