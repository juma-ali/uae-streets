#!/usr/bin/env node
/**
 * Assigns a locality to every road that has no admin district.
 *
 *   node tools/localities.mjs
 *
 * Why: 454 roads fall outside every `admin_level 8/10` polygon — most of Dubai's
 * newer areas. The admin boundaries do not exist there, but OSM's `place=*` nodes
 * do, and they carry the name people actually use (Al Barsha, Dubai Knowledge Park).
 *
 * The place nodes are fetched once from Overpass into .cache/places.json:
 *
 *   node["place"~"^(city|town|village|hamlet|suburb|neighbourhood|quarter|locality|isolated_dwelling)$"]["name"]
 *
 * A road takes the nearest node, but a real settlement wins over a lone hamlet:
 * suburbs and neighbourhoods outrank villages, which outrank localities.
 */

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const load = (f, g) => {
  const box = {};
  new Function("window", readFileSync(root + f, "utf8"))(box);
  return box[g];
};

const PLACES = JSON.parse(readFileSync(root + ".cache/places.json", "utf8"));
const KB = load("data/kb.js", "KB");

/* denser settlement first */
const RANK = { neighbourhood: 1, suburb: 1, quarter: 1, town: 2, village: 2, city: 3, hamlet: 4, locality: 4, isolated_dwelling: 5 };
const MAX_KM = 6;

const km = (aLat, aLon, bLat, bLon) => {
  const dLat = (bLat - aLat) * 111.32;
  const dLon = (bLon - aLon) * 111.32 * Math.cos((aLat * Math.PI) / 180);
  return Math.sqrt(dLat * dLat + dLon * dLon);
};

const unplaced = KB.streets.filter((s) => !s.area && s.lat != null && s.lon != null);
const out = {};
const stats = { assigned: 0, tooFar: 0, outside: 0 };

for (const s of unplaced) {
  let best = null;
  for (const p of PLACES) {
    const d = km(s.lat, s.lon, p.lat, p.lon);
    if (d > MAX_KM) continue;
    const rank = RANK[p.place] || 5;
    if (!best || rank < best.rank || (rank === best.rank && d < best.d)) best = { p, d, rank };
  }
  if (best) {
    out[s.osm] = [best.p.name, best.p.name_ar || best.p.name, best.p.place];
    stats.assigned++;
  } else stats.tooFar++;
}

writeFileSync(
  root + "data/localities.js",
  "/* Locality for roads outside every admin district, from OSM place nodes.\n" +
    "   Generated by tools/localities.mjs — do not edit by hand. */\n" +
    "window.LOCALITIES = " + JSON.stringify(out) + ";\n"
);

const byPlace = {};
Object.values(out).forEach((v) => (byPlace[v[2]] = (byPlace[v[2]] || 0) + 1));
console.log(`unplaced roads: ${unplaced.length} | assigned: ${stats.assigned} | too far: ${stats.tooFar}`);
console.log("by place type:", JSON.stringify(byPlace));
const samples = Object.entries(out).slice(0, 6).map(([k, v]) => `${k} → ${v[0]} (${v[2]})`);
console.log(samples.join("\n"));
