#!/usr/bin/env node
/**
 * Assigns one of the guide's five categories to every street in the KB.
 *
 *   People  — a ruler, founder, or member of a ruling family, or any named individual
 *   Places  — a district, well, harbour, hill or other landmark the road passes
 *   Words   — an abstract noun or natural feature used as a value or image
 *   Tribes  — a bare family or tribal name (Al Nuaimi, Bani Yas)
 *   Events  — a date or national milestone
 *
 *   node tools/classify.mjs            → report + data/categories.js
 *
 * The decision is made on the head noun of the Arabic name, because Arabic
 * personal names contain the same words as everything else: "Eid Bin Musabeh"
 * is a person, not a festival; "Umm Ghafah" is a place, not a person.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const box = {};
new Function("window", readFileSync(root + "data/kb.js", "utf8"))(box);
const KB = box.KB;

const norm = (s) =>
  String(s || "")
    .replace(/[\u064B-\u0655\u0670\u0640]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/\s+/g, " ")
    .trim();

const headAr = (s) => {
  const parts = norm(s.name_ar).replace(/^(شارع|طريق|جادة|ممر|حارة|زقاق|درب|نهج)\s+/, "").split(" ");
  return parts[0] || "";
};
const firstEn = (s) => (s.name_en || "").trim().split(/\s+/)[0].toLowerCase();

/* Landforms and built landmarks: the Places category. */
const GEO = new Set(
  `طوي وادي جبل يو سيح بدع غليل رمله برقا نقا غيط راس غافات قرن عرقوب عرق سبخه شعبه خور محضر رقعه برج حدبه دوار جزيره عود شرف ثنيه وعبه قصر حصن سوق مزرعه بستان فلج عين بير ميناء كورنيش جسر نفق مطار حديقه ساحه محطه مصلي شاطئ خليج بحيره حديقه`
    .split(/\s+/)
);
const GEO_EN = /(^|\s)(tawi|sayh|wadi|jabal|jebel|niqa|arqoub|hadbah|qarn|ras|jazirat|jazeera|khor|sabkha|raml|ruwaydat|bad'|qal'at|hisn|suq|port|island|hill|valley|creek|corniche|bridge|tunnel|airport|park|square|roundabout)(\s|$)/i;

/* Given names: a street starting with one is named after a person. */
const GIVEN = new Set(
  `محمد احمد علي سعيد عمر سيف سعد عبدالله خليفه زايد راشد مكتوم حمدان سلطان طحنون هزاع منصور فيصل خالد سالم حميد ماجد عمار حشر جمعه عبيد ميثاء فاطمه عائشه شما لطيفه مريم حصه سلامه موزه شيخه ريسه مبارك بطي سهيل مروان عيسي موسي يوسف ابراهيم اسحاق اسماعيل جاسم ربيع ثاني سيف سعيد`
    .split(/\s+/)
);

/* Family and tribal names: bare ones are the Tribes category. */
const FAMILY = new Set(
  `نهيان مكتوم قاسمي نعيمي معلا شرقي فلاسي مزروعي سويدي كتبي ظاهري منصوري شامسي زعابي مرر كعبي بلوشي حميري رميثي قمزي فلاحي شرياني قبيسي درعي شفار تاير حمادي نقبي حفيتي تنيجي عطيش`
    .split(/\s+/)
);

const EVENT = /(ittihad|etihad|wahda|istiqlal|ihtifal|mihrajan|expo|festival|national day|2nd december|second december|jubilee|anniversary)/i;
const EVENT_AR = /(اتحاد|وحده|استقلال|احتفال|مهرجان|اكسبو|يوبيل|ذكري)/;

const PERSON_EN = /(^|\s)(bin|bint|ibn|abdul|abdullah|abdur|abd|sheikh|shaikh|sheikha|shaheed|marty?r)(\s|$)/i;
const PERSON_AR = /(^|\s)(بن|بنت|عبد|الشيخ|الشيخه|الشهيد)(\s|$)/;

const GEO_WORDS_EN = /(^|\s)(tawi|sayh|wadi|jabal|jebel|niqa|arqoub|hadbah|qarn|ras|jazirat|khor|sabkha|raml|bad'|qal'at|hisn|suq)(\s|$)/i;

function classify(s) {
  const n = s.name_en || "";
  const a = s.name_ar || "";
  const h = headAr(s);
  const tokens = n.trim().split(/\s+/);

  if (EVENT.test(n) || EVENT_AR.test(norm(a))) return "event";

  // a person: patronymic markers, or a given name as the head
  if (PERSON_EN.test(n) || PERSON_AR.test(norm(a))) return "person";
  if (GIVEN.has(h)) return "person";
  if (tokens.length >= 2 && GIVEN.has(norm(tokens[0]))) return "person";

  // a bare family name is a tribe; "given + family" is already a person above
  // family names are Arabic, so compare the Arabic head with its article removed
  const hBare = h.replace(/^ال/, "");
  if (FAMILY.has(hBare)) return "tribe";
  if (/^bani\b/i.test(n) || /^بني\b/.test(norm(a))) return "tribe";

  // places: landforms, landmarks, districts
  if (GEO.has(h)) return "place";
  if (GEO_EN.test(n) || GEO_WORDS_EN.test(n)) return "place";

  return "word";
}

const counts = {};
const samples = {};
const mapping = {};
for (const s of KB.streets) {
  const c = classify(s);
  mapping[s.osm] = c;
  counts[c] = (counts[c] || 0) + 1;
  (samples[c] = samples[c] || []).push(s.name_en || s.name_ar);
}

writeFileSync(
  root + "data/categories.js",
  "/* Category per street: people | places | words | tribes | events.\n" +
    "   Generated by tools/classify.mjs — do not edit by hand. */\n" +
    "window.STREET_CATEGORIES = " + JSON.stringify(mapping) + ";\n"
);

console.log("categories:", JSON.stringify(counts), "of", KB.streets.length);
for (const c of ["person", "place", "word", "tribe", "event"]) {
  console.log(`\n${c} (${counts[c] || 0}):`);
  console.log("   " + [...new Set(samples[c] || [])].slice(0, 8).join(" · "));
}
console.log("\nwrote data/categories.js");
